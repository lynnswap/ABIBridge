#!/usr/bin/env python3
"""Generate only NSObjectProtocol's imported requirement names.

Read the compiler importer and ARC/Swift availability from every installed SDK
of each --developer-dir. Merge the names with the checked-in union unless
--replace is requested. --check verifies coverage without changing the file.
"""
import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'Sources/ABIBridge/SwiftObjectiveCRequirementNames.swift'
SDKS = [('macosx', 'arm64-apple-macos15.4'), ('iphoneos', 'arm64-apple-ios18.4'),
        ('appletvos', 'arm64-apple-tvos18.4'), ('watchos', 'arm64_32-apple-watchos11.4'),
        ('xros', 'arm64-apple-xros2.4')]
USR = re.compile(r'^c:(?:@M@\w+@)?objc\(pl\)NSObject\((im|cm|py|cpy)\)(.+)$')


def run(command, env, **kwargs):
    return subprocess.run(command, env=env, text=True, capture_output=True, check=True, **kwargs).stdout


def scan_sdk(sdk, target, env, directory):
    directory.mkdir(parents=True, exist_ok=True)
    run(['xcrun', 'swift-symbolgraph-extract', '-module-name', 'ObjectiveC', '-sdk', str(sdk),
         '-target', target, '-minimum-access-level', 'private', '-output-dir', str(directory)], env)
    rows = set()
    for path in directory.glob('*.symbols.json'):
        data = json.loads(path.read_text())
        optional = {r['source'] for r in data.get('relationships', []) if r['kind'] == 'optionalRequirementOf'}
        for symbol in data['symbols']:
            usr = symbol['identifier']['precise']
            match = USR.match(usr)
            if not match:
                continue
            side, selector = match.groups()
            kind = 'getter' if side in ('py', 'cpy') else 'method'
            name = symbol['names']['title']
            declaration = ''.join(f['spelling'] for f in symbol.get('declarationFragments', []))
            is_optional = usr in optional or bool(re.search(r'\boptional\b', declaration))
            rows.add((selector, kind, side in ('im', 'py'), name, is_optional))
    ast = run(['xcrun', 'clang', '-target', target, '-fobjc-arc', '-isysroot', str(sdk),
               '-x', 'objective-c', '-Xclang', '-ast-dump', '-Xclang', '-ast-dump-filter=NSObject',
               '-fsyntax-only', '-'], env, input='#import <objc/NSObject.h>\n')
    protocol = ast.split('ObjCProtocolDecl ', 1)[1].split('\n\n', 1)[0]
    methods = {}
    current = None
    for line in protocol.splitlines():
        match = re.search(r'^[|`]-ObjCMethodDecl .*? ([-+]) ([^ ]+) \'', line)
        if match:
            current = (match[2], match[1] == '-')
            methods[current] = False
        elif re.match(r'^[|`]-\w+Decl ', line):
            current = None
        elif current and ('UnavailableAttr ' in line or ('AvailabilityAttr ' in line and ' swift ' in line and ' Unavailable ' in line)):
            methods[current] = True
    for (selector, instance), unavailable in methods.items():
        if unavailable:
            rows.add((selector, 'method', instance, '', False))
        elif not any(row[0] == selector and row[2] == instance for row in rows):
            raise RuntimeError(f'{sdk}: NSObject selector {selector} is neither named nor unavailable in Swift')
    return rows


def checked_in():
    if not OUTPUT.exists():
        return set()
    rows = set()
    for line in OUTPUT.read_text().splitlines():
        match = re.match(r'^\s+(".*"),$', line)
        if match:
            selector, kind, side, member, optional = json.loads(match[1]).split('\t')
            rows.add((selector, kind, side == 'instance', member, optional == 'optional'))
    return rows


def write(rows):
    text = """// Generated by scripts/generate-objc-requirement-names.py.
// Only NSObjectProtocol has generated names; unknown selectors use shape.
struct SwiftObjectiveCRequirementName: Sendable {
    let selector: String
    let role: SwiftObjectiveCMemberShape.Role
    let isInstance: Bool
    let member: String
    let isOptional: Bool

    func matches(role: SwiftObjectiveCMemberShape.Role, isStatic: Bool, optionalResult: Bool) -> Bool {
        !member.isEmpty && self.role == role && isInstance != isStatic
            && (!isOptional || (role == .getter && optionalResult))
    }
}

// selector, Swift member kind, side, Swift member name (empty if unavailable), optionality.
let swiftNSObjectRequirementNames: [SwiftObjectiveCRequirementName] = [
"""
    for selector, kind, instance, member, optional in sorted(rows):
        row = '\t'.join([selector, kind, 'instance' if instance else 'class', member,
                         'optional' if optional else 'required'])
        text += '    ' + json.dumps(row) + ',\n'
    text += """].map { encoded in
    let fields = encoded.split(separator: "\\t", omittingEmptySubsequences: false)
    return .init(
        selector: String(fields[0]), role: fields[1] == "getter" ? .getter : .method,
        isInstance: fields[2] == "instance", member: String(fields[3]),
        isOptional: fields[4] == "optional"
    )
}
"""
    OUTPUT.write_text(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--developer-dir', action='append')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--replace', action='store_true')
    args = parser.parse_args()
    found = set()
    with tempfile.TemporaryDirectory(prefix='abi-nsobject-names-') as temp:
        for index, developer in enumerate(args.developer_dir or [None]):
            env = dict(os.environ)
            if developer:
                env['DEVELOPER_DIR'] = developer
            for name, target in SDKS:
                sdk = subprocess.run(['xcrun', '--sdk', name, '--show-sdk-path'], env=env, capture_output=True, text=True)
                if sdk.returncode:
                    continue
                found |= scan_sdk(Path(sdk.stdout.strip()), target, env, Path(temp) / str(index) / name)
    if not found:
        raise RuntimeError('No SDK supplied NSObjectProtocol declarations')
    existing = checked_in()
    if args.check:
        missing = found - existing
        if missing:
            raise RuntimeError(f'NSObjectProtocol names need regeneration: {sorted(missing)}')
        print(f'NSObjectProtocol names cover {len(found)} SDK declarations')
    else:
        write(found if args.replace else found | existing)
        print(f'Wrote {len(found if args.replace else found | existing)} NSObjectProtocol declarations')


if __name__ == '__main__':
    main()
